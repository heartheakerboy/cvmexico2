/**
 * Get a job config by template ID
 */
export function getJobConfig(templateId: string): JobConfig | undefined {
  return JOB_CONFIGS.find((c) => c.id === templateId);
}

/**
 * Get all configs for a specific engine
 */
export function getConfigsByEngine(engine: JobConfig["engine"]): JobConfig[] {
  return JOB_CONFIGS.filter((c) => c.engine === engine);
}
