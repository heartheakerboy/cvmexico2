# Qué cuenta como experiencia cuando nunca has trabajado

El error más común es pensar que esta sección debe quedar vacía. En realidad, casi todos los candidatos sin empleo formal tienen experiencia valiosa sin saberlo:

- Prácticas profesionales y servicio social: son experiencia laboral real y las empresas en México las valoran como tal
- Proyectos escolares relevantes: investigaciones, prototipos, campañas o sistemas que construiste en la universidad
- Voluntariado: trabajo en organizaciones, eventos o comunidades, aunque no haya sido remunerado
- Negocios familiares o emprendimientos: ventas, atención a clientes, redes sociales o administración básica
- Actividades extracurriculares: equipos deportivos, sociedades de alumnos, clubes de debate o robótica
- Cursos y certificaciones: cursos de Google, Microsoft, Cisco, idiomas o herramientas de tu área

La clave no es la lista, sino cómo la describes: con verbos de acción y resultados medibles siempre que sea posible.

# Estructura recomendada para un CV sin experiencia

El orden de las secciones cambia cuando no tienes historial laboral. Tu formación y tus habilidades deben ir primero, porque son tu evidencia más fuerte.

## 1. Datos de contacto profesionales

Incluye solo nombre completo, ciudad y estado, teléfono, correo electrónico y, si tienes, tu perfil de LinkedIn. Usa un correo serio con tu nombre, por ejemplo nombre.apellido@gmail.com. No incluyas CURP, RFC, estado civil ni tu dirección completa: por seguridad y porque la ley de protección de datos no lo requiere en esta etapa.

## 2. Objetivo o resumen profesional

Son tres o cuatro líneas que responden: quién eres, qué sabes hacer y qué buscas. Debe adaptarse a cada vacante, usando las palabras clave del anuncio. Más abajo encontrarás tres ejemplos listos para adaptar.

## 3. Formación académica

Coloca tu último nivel de estudios: nombre de la carrera o bachillerato, institución y fechas. Si tu promedio es de 9 o superior, inclúyelo: para un primer empleo es una señal que los reclutadores sí consideran. Agrega materias o proyectos relevantes solo si se relacionan con la vacante.

## 4. Experiencia práctica

Aquí van tus prácticas, servicio social, proyectos y voluntariado, en orden cronológico inverso. Describe cada uno con viñetas que empiecen con verbos como: apoyé, organicé, diseñé, atendí, registré, elaboré, coordiné o presenté. Si puedes agregar un número, hazlo: no es lo mismo "atendí clientes" que "atendí a más de 30 clientes por día".

## 5. Habilidades

Separa tus habilidades técnicas (Excel, Canva, Python, inglés intermedio, manejo de caja) de tus habilidades blandas (trabajo en equipo, puntualidad, comunicación). Prioriza las que la vacante mencione: los sistemas ATS comparan tu CV contra esa lista.

## 6. Idiomas y cursos adicionales

Indica cada idioma con su nivel real (básico, intermedio, avanzado o certificación). Después, lista cursos y certificaciones con la institución y el año.

# Tres ejemplos de objetivo profesional

Adapta estos ejemplos a tu perfil y a la vacante. Evita frases genéricas como "busco una empresa donde crecer": todas las vacantes las descartan por repetidas.

## Para administración o atención al cliente

Estudiante de Administración con experiencia en servicio social atendiendo a más de 30 usuarios diarios y manejo de Excel intermedio. Busco mi primer empleo en atención al cliente aplicando organización, registro de información y trato cordial con el público.

## Para sistemas o tecnología

Recién egresado de Ingeniería en Sistemas con proyectos académicos en Python y bases de datos MySQL. Certificación en fundamentos de redes. Busco una posición junior donde aplicar desarrollo, documentación y soporte técnico a usuarios.

## Para ventas o comercio

Persona con experiencia atendiendo el negocio familiar durante 2 años: ventas, cobro en efectivo y tarjeta, y control de inventario. Manejo de redes sociales para promocionar productos. Busco integrarme a un equipo de ventas donde aportar trato directo con el cliente y cumplimiento de metas.

# Errores que hacen que descarten tu CV

- Usar una plantilla con columnas, tablas o gráficos: muchos sistemas ATS no los leen y tu CV se descarta antes de llegar a una persona
- Enviar el mismo CV a todas las vacantes sin adaptar palabras clave ni objetivo
- Incluir datos sensibles como CURP, RFC o dirección completa
- Errores de ortografía: en perfiles sin experiencia, un error tipográfico pesa el doble
- Extender el CV a más de una página sin tener contenido que lo justifique
- Poner referencias o la frase "referencias disponibles a petición": ya no se usa

# Cómo pasar los filtros ATS en tu primer empleo

Antes de que un reclutador vea tu currículum, un software llamado ATS lo revisa buscando coincidencias con la vacante. Para perfiles junior esto es una ventaja si sabes usarla:

- Copia el lenguaje de la vacante: si piden "atención a clientes", usa exactamente esa frase en lugar de un sinónimo
- Usa títulos de sección estándar: Experiencia, Educación, Habilidades
- Guarda y envía siempre en PDF con texto seleccionable, nunca como imagen
- No pongas información importante en encabezados, pies de página o imágenes
- Incluye la palabra clave de la vacante solo cuando de verdad tengas esa habilidad: el ATS te clasifica, pero la entrevista confirma

